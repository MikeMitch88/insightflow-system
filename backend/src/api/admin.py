def _load_settings() -> dict:
    if SETTINGS_FILE.exists():
        try:
            return json.loads(SETTINGS_FILE.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            pass
    return DEFAULT_SETTINGS.copy()


def _save_settings(data: dict) -> None:
    SETTINGS_FILE.parent.mkdir(parents=True, exist_ok=True)
    SETTINGS_FILE.write_text(json.dumps(data, indent=2), encoding="utf-8")


def _load_audit_logs() -> list[dict]:
    if AUDIT_FILE.exists():
        try:
            return json.loads(AUDIT_FILE.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            pass
    return DEFAULT_AUDIT_LOGS.copy()


def _save_audit_logs(logs: list[dict]) -> None:
    AUDIT_FILE.parent.mkdir(parents=True, exist_ok=True)
    AUDIT_FILE.write_text(json.dumps(logs, indent=2), encoding="utf-8")


def _load_notifications() -> list[dict]:
    if NOTIFICATIONS_FILE.exists():
        try:
            return json.loads(NOTIFICATIONS_FILE.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            pass
    return DEFAULT_NOTIFICATIONS.copy()


def _save_notifications(notifications: list[dict]) -> None:
    NOTIFICATIONS_FILE.parent.mkdir(parents=True, exist_ok=True)
    NOTIFICATIONS_FILE.write_text(json.dumps(notifications, indent=2), encoding="utf-8")


def create_notification(recipient_role: str, title: str, message: str, report_id: Optional[int] = None, notif_type: str = "general") -> dict:
    """Create a persistent notification for target role(s)."""
    notifications = _load_notifications()
    new_notif = {
        "id": len(notifications) + 1,
        "recipient_role": recipient_role,
        "title": title,
        "message": message,
        "report_id": report_id,
        "type": notif_type,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "read": False
    }
    notifications.insert(0, new_notif)
    _save_notifications(notifications[:100])
    return new_notif


class SettingsUpdate(BaseModel):
    orgName: Optional[str] = None
    reportingFrequency: Optional[str] = None
    emailNotifications: Optional[bool] = None
    defaultPeriod: Optional[str] = None
    autoGenerateDonorReport: Optional[bool] = None
    scheduledDeliveryDay: Optional[str] = None
    escalationReminderDays: Optional[int] = None


class UserStatusUpdate(BaseModel):
    status: Optional[str] = None
    role: Optional[str] = None


class AuditLogCreate(BaseModel):
    user: str
    action: str
    details: str
    category: Optional[str] = "General"


@router.get("/admin/settings")
def get_settings():
    return _load_settings()


@router.put("/admin/settings")
def update_settings(body: SettingsUpdate):
    current = _load_settings()
    updates = body.model_dump(exclude_unset=True)
    current.update(updates)
    _save_settings(current)
    
    logs = _load_audit_logs()
    logs.insert(0, {
        "id": len(logs) + 1,
        "timestamp": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"),
        "user": "Program Administrator",
        "action": "Updated System Settings",
        "details": f"Updated settings: {list(updates.keys())}",
        "category": "Settings",
    })
    _save_audit_logs(logs[:50])
    return current



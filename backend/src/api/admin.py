@router.get("/notifications")
def get_notifications(role: Optional[str] = Query(None)):
    """Retrieve notifications filtered for current user role."""
    all_notifs = _load_notifications()
    if role:
        target = role.lower()
        filtered = [
            n for n in all_notifs 
            if n.get("recipient_role", "").lower() == target or n.get("recipient_role") == "all"
            or (target in ["program_manager", "leadership"] and n.get("recipient_role") in ["program_manager", "leadership"])
        ]
    else:
        filtered = all_notifs

    unread_count = sum(1 for n in filtered if not n.get("read", False))
    return {
        "notifications": filtered,
        "unread_count": unread_count,
        "total": len(filtered)
    }


@router.post("/notifications/{notification_id}/read")
def mark_notification_read(notification_id: int):
    """Mark a notification as read."""
    notifications = _load_notifications()
    for n in notifications:
        if n["id"] == notification_id:
            n["read"] = True
            break
    _save_notifications(notifications)
    return {"status": "success", "id": notification_id}


@router.post("/notifications/clear-all")
def clear_all_notifications(role: Optional[str] = Query(None)):
    """Mark all notifications as read."""
    notifications = _load_notifications()
    for n in notifications:
        if not role or n.get("recipient_role", "").lower() == role.lower() or role.lower() == "all":
            n["read"] = True
    _save_notifications(notifications)
    return {"status": "success"}
